// Package demo выводит фактический и ожидаемый результаты маленького примера.
// Он не содержит решений задач; совпадение одного примера не заменяет тесты.
package demo

import (
	"fmt"
	"io"
	"reflect"
)

// Print сравнивает уже вычисленные значения, не изменяя и не исправляя их.
// bool из контракта показывается вместе с результатом: ноль без found/ok
// может означать как корректное значение, так и отсутствие реализации.
func Print(out io.Writer, name string, input, got, want any) {
	fmt.Fprintf(out, "\nАлгоритм: %s\nВход: %v\nПолучено: %v\nОжидается: %v\n", name, input, got, want)
	if reflect.DeepEqual(got, want) {
		fmt.Fprintln(out, "Пример совпал. Полную корректность проверяют тесты.")
	} else {
		fmt.Fprintln(out, "Результаты отличаются — проверь реализацию.")
	}
}
